/** Real string hash (djb2-ish), not just the first character -- the old
 * seed (id.charCodeAt(0)) only produced ~16 distinct values for a
 * hex-first-char UUID regardless of pool size, so most of a 20-image pool
 * could never even be reached. This spreads across the full pool. */
export function communitySeed(id: string | null | undefined): number {
  const s = id || "x";
  let h = 5381;
  for (let i = 0; i < s.length; i++) {
    h = (h * 33) ^ s.charCodeAt(i);
  }
  return Math.abs(h);
}

export function getCategoryImage(slug: string, seed: number, size: { w: number; h: number } = { w: 640, h: 360 }) {
  const pool = CAT_IMAGES[slug] || CAT_IMAGES.other;
  const photo = pool[Math.abs(seed || 0) % pool.length];
  return `${photo.raw}?w=${size.w}&h=${size.h}&fit=crop&q=80&auto=format`;
}

/** A specific entity's own persisted assignment (src/lib/unsplash.ts) wins
 * when present; the deterministic pool pick is the fallback for rows that
 * predate that system and haven't been backfilled yet. */
export function resolveEntityImage(
  unsplashImageUrl: string | null | undefined,
  slug: string,
  seed: number,
  size: { w: number; h: number } = { w: 640, h: 360 },
) {
  if (unsplashImageUrl) return `${unsplashImageUrl}?w=${size.w}&h=${size.h}&fit=crop&q=80&auto=format`;
  return getCategoryImage(slug, seed, size);
}

/** Exposed for src/lib/unsplash.ts -- per-entity assignment picks a photo
 * from this same verified pool (rather than a live search per entity,
 * which the API's 50/hour demo-tier rate limit can't sustain) and needs
 * the photo's real id to fire the required download-tracking ping. */
export function getCategoryPool(slug: string): CatImage[] {
  return CAT_IMAGES[slug] || CAT_IMAGES.other;
}
